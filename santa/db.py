import sqlite3
from contextlib import contextmanager

from flask import current_app, g

SCHEMA = """
CREATE TABLE IF NOT EXISTS events (
    id INTEGER PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    generated_at TEXT
);
CREATE TABLE IF NOT EXISTS participants (
    id INTEGER PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id),
    name TEXT NOT NULL,
    name_key TEXT NOT NULL,
    registered_at TEXT,
    token_hash TEXT UNIQUE,
    UNIQUE(event_id, name_key),
    UNIQUE(event_id, id),
    CHECK ((registered_at IS NULL) = (token_hash IS NULL))
);
CREATE TABLE IF NOT EXISTS assignments (
    event_id INTEGER NOT NULL,
    giver_id INTEGER NOT NULL,
    recipient_id INTEGER NOT NULL,
    PRIMARY KEY (event_id, giver_id),
    UNIQUE (event_id, recipient_id),
    CHECK (giver_id <> recipient_id),
    FOREIGN KEY (event_id, giver_id) REFERENCES participants(event_id, id),
    FOREIGN KEY (event_id, recipient_id) REFERENCES participants(event_id, id)
);
CREATE TABLE IF NOT EXISTS activity (
    id INTEGER PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id),
    participant_id INTEGER,
    action TEXT NOT NULL,
    status TEXT NOT NULL,
    occurred_at TEXT NOT NULL,
    FOREIGN KEY (event_id, participant_id) REFERENCES participants(event_id, id)
);
"""


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        return self.connection.execute(query.replace("?", "%s"), params)

    def executemany(self, query, params):
        with self.connection.cursor() as cursor:
            cursor.executemany(query.replace("?", "%s"), params)

    def close(self):
        self.connection.close()


def db():
    if "db" not in g:
        if current_app.config["DATABASE_URL"]:
            import psycopg
            from psycopg.rows import dict_row

            g.db = PostgresConnection(psycopg.connect(
                current_app.config["DATABASE_URL"], row_factory=dict_row,
                autocommit=True, connect_timeout=5,
            ))
        else:
            g.db = sqlite3.connect(current_app.config["DATABASE"], timeout=10, isolation_level=None)
            g.db.row_factory = sqlite3.Row
            g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


def close_db(_error=None):
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()


@contextmanager
def write_transaction():
    connection = db()
    if isinstance(connection, PostgresConnection):
        with connection.connection.transaction():
            # Serialize writes across web workers and startup migrations.
            connection.execute("SELECT pg_advisory_xact_lock(635718024)")
            yield connection
    else:
        connection.execute("BEGIN IMMEDIATE")
        try:
            yield connection
            connection.commit()
        except BaseException:
            connection.rollback()
            raise


def migrate():
    schema = SCHEMA
    if isinstance(db(), PostgresConnection):
        schema = schema.replace("id INTEGER PRIMARY KEY", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    migrations = [schema + """
        CREATE INDEX IF NOT EXISTS activity_event ON activity(event_id, id);
        CREATE INDEX IF NOT EXISTS activity_participant ON activity(event_id, participant_id, action);
    """]
    with write_transaction() as connection:
        connection.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)")
        applied = {row["version"] for row in connection.execute("SELECT version FROM schema_migrations")}
        for version, script in enumerate(migrations, start=1):
            if version in applied:
                continue
            for statement in script.split(";"):
                if statement.strip():
                    connection.execute(statement)
            connection.execute("INSERT INTO schema_migrations (version) VALUES (?)", (version,))
